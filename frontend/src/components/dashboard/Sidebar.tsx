          <p className="px-3 mb-2 text-[11px] font-semibold text-text-muted uppercase tracking-widest">Menu</p>
          {visibleItems.map((item) => {
            const isActive = pathname === item.href || pathname.startsWith(item.href + "/");
            return (
              <Link
                key={item.href}
                href={item.href}
                onClick={onClose}
                className={`
                  flex items-center gap-3 px-3 py-2.5 rounded-xl text-[14px]
                  transition-all duration-150
                  ${
                    isActive
                      ? "bg-surface-3 text-text-primary font-medium"
                      : "text-text-secondary hover:bg-surface-2 hover:text-text-primary"
                  }
                `}
              >
                <span className={isActive ? "text-accent-400" : "text-text-muted"}>
                  {item.icon}
                </span>
                {item.label}
              </Link>
            );
          })}
